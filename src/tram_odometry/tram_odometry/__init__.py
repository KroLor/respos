"""Резервная одометрия трамвая: нода ROS 2 и ядро без ROS."""
import os

# Один поток BLAS — до первого импорта numpy (его импортируют сообщения ROS и модель движения).
# По умолчанию OpenBLAS раздаёт даже операции над матрицами 2×2 потокам по числу ядер, и те
# крутятся в ожидании: нода занимала ~8 ядер при лимите ТЗ в 2. С одним потоком процессорное
# время модели меньше в ~14 раз. Пакет импортируется раньше модуля ноды, поэтому это здесь.
for _variable in ('OPENBLAS_NUM_THREADS', 'OMP_NUM_THREADS', 'MKL_NUM_THREADS'):
    os.environ.setdefault(_variable, '1')
